            ar[key] ?: en[key] ?: key
        } else {
            en[key] ?: key
        }
        return try {
            if (args.isNotEmpty()) {
                String.format(formatStr, *args)
            } else {
                formatStr
            }
        } catch (e: Exception) {
            formatStr
        }
    }
